"""Generate tokens.css and tokens.js from tokens.json.

Usage: python3 generate_tokens.py
"""
import json
import pathlib

here = pathlib.Path(__file__).parent
t = json.loads((here / "tokens.json").read_text())


def colors(theme):
    return "\n".join(f"  --color-{k}: {v};" for k, v in t["colors"][theme].items())


lines = ["/* Generated by generate_tokens.py from tokens.json. Do not edit by hand. */", ":root {"]
lines.append(colors("light"))

fam = t["typography"]["families"]
lines.append(f'  --font-brand: "{fam["brand"]}", Georgia, serif;')
lines.append(f'  --font-ui: "{fam["ui"]}", system-ui, sans-serif;')
for name, s in t["typography"]["scale"].items():
    lines.append(f"  --type-{name}: {s['weight']} {s['size']}px/{s['lineHeight']}px var(--font-{s['family']});")
for k, v in t["space"].items():
    lines.append(f"  --space-{k}: {v}px;")
for k, v in t["radius"].items():
    lines.append(f"  --radius-{k}: {v}px;")
for k, v in t["elevation"].items():
    lines.append(f"  --elevation-{k}: {v};")
for k, v in t["motion"]["duration"].items():
    lines.append(f"  --duration-{k}: {v}ms;")
for k, v in t["motion"]["easing"].items():
    lines.append(f"  --easing-{k}: {v};")
lines.append("  color-scheme: light;")
lines.append("}")

dark = colors("dark")
lines += [
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    dark.replace("  --", "    --"),
    "    color-scheme: dark;",
    "  }",
    "}",
    ':root[data-theme="dark"] {',
    dark,
    "  color-scheme: dark;",
    "}",
]
(here / "tokens.css").write_text("\n".join(lines) + "\n")
# JS copy so the style guide page can read the tokens even when opened via file://
(here / "tokens.js").write_text(
    "// Generated by generate_tokens.py from tokens.json. Do not edit by hand.\n"
    f"window.TOKENS = {json.dumps(t, ensure_ascii=False, indent=2)};\n"
)
print("tokens.css and tokens.js updated")
